import { test, expect } from '@playwright/test'
import path from 'node:path'

test('project overview creates and removes an explicit evidence link', async ({ page, request }, info) => {
  const projectResponse = await request.post('/api/v1/projects', { data: { name: '合成关联验收' } })
  expect(projectResponse.status()).toBe(201)
  const project = await projectResponse.json()
  const conversation = await (await request.post('/api/v1/conversations', { data: { title: '关联测试' } })).json()
  try {
    const turn = await request.post(`/api/v1/conversations/${conversation.id}/turns`, { data: { message: '合成数据', expected_revision: 0, client_request_id: crypto.randomUUID() } })
    expect(turn.ok()).toBeTruthy()
    const current = await (await request.get(`/api/v1/conversations/${conversation.id}`)).json()
    const membership = await request.put(`/api/v1/projects/${project.id}/conversations/${conversation.id}`, { data: { expected_revision: 0, expected_conversation_revision: current.revision, expected_metadata_revision: current.metadata_revision, expected_source_project_id: null } })
    expect(membership.ok(), await membership.text()).toBeTruthy()
    await page.goto(`/projects/${project.id}/knowledge`)
    await page.getByLabel('选择文件（断线后可重选同一文件核对）').setInputFiles({ name: 'synthetic.md', mimeType: 'text/markdown', buffer: Buffer.from('# 合成文献\n银河潮汐 synthetic evidence\n') })
    await page.getByRole('button', { name: '保存文件并本地解析' }).click()
    await expect(page.getByRole('heading', { name: 'synthetic.md', exact: true, level: 3 })).toBeVisible({ timeout: 30000 })
    await page.getByLabel('问题中的明确关键词').fill('银河潮汐')
    await page.getByRole('button', { name: '检索原文证据' }).click()
    await page.getByRole('button', { name: '核对引用与原始版本' }).first().click()
    await page.getByRole('link', { name: '关联此原文与项目结果' }).click()
    await expect(page.getByRole('heading', { name: '来源关联' })).toBeVisible()
    const target = page.getByLabel('同项目结果')
    await expect(target.locator('option')).toHaveCount(2)
    await target.selectOption({ index: 1 })
    await page.getByLabel('用户备注（可选，最多1000字）').fill('合成备注')
    const create = page.getByRole('button', { name: '核对后建立关联' })
    await expect(create).toBeEnabled()
    await create.click()
    await expect(page.getByRole('dialog')).toContainText('合成备注')
    await page.getByRole('dialog').getByRole('button', { name: '取消' }).click()
    await expect(page.getByRole('dialog')).not.toBeVisible()
    await expect(page.getByRole('heading', { name: '项目关联 0/1000' })).toBeVisible()
    await create.click()
    await page.getByRole('dialog').getByRole('button', { name: '确认关联这两项' }).click()
    await expect(page.getByText('已建立用户引用关系', { exact: false })).toBeVisible()
    await expect(page.getByLabel('来源核对').getByText('银河潮汐 synthetic evidence', { exact: false })).toBeVisible()
    if (process.env.ASTROAGENT_RECORD_DIR) await page.screenshot({ path: path.join(process.env.ASTROAGENT_RECORD_DIR, `${info.project.name}-overview.png`) })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: '核对两端' }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: '仅解除关联' }).click()
    await page.getByRole('dialog').getByRole('button', { name: '确认只解除关联' }).click()
    await expect(page.getByText('已解除关联', { exact: false })).toBeVisible()
  } finally {
    const detail = await (await request.get(`/api/v1/projects/${project.id}`)).json()
    await request.delete(`/api/v1/projects/${project.id}`, { data: { expected_revision: detail.revision, confirm: true } })
    const latest = await (await request.get(`/api/v1/conversations/${conversation.id}`)).json()
    await request.delete(`/api/v1/conversations/${conversation.id}`, { data: { expected_revision: latest.revision, confirm: true } })
  }
})
