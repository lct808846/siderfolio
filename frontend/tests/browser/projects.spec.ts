import { test, expect } from '@playwright/test'
import { mkdirSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { chooseUiOption } from './ui-select'

test('projects: full snapshots, explicit rerun, compare, ZIP recovery and preserved conversations', async ({ page, request, browser }, info) => {
  info.annotations.push({ type: 'browser_version', description: browser.version() })
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  const ownedProjects = new Set<string>(), ownedConversations = new Set<string>()
  const screenshot = async (name: string) => { if (process.env.ASTROAGENT_RECORD_DIR) { mkdirSync(process.env.ASTROAGENT_RECORD_DIR, { recursive: true }); await page.screenshot({ animations: 'disabled', path: path.join(process.env.ASTROAGENT_RECORD_DIR, `${info.project.name}-project-${name}.png`) }) } }
  const projectName = '候选源复核项目'
  const openManager = async (name: string, id: string) => {
    const projectLink = page.locator('a[href="/?project=' + id + '"]')
    const row = page.locator('.settings-row').filter({ has: projectLink })
    await row.getByRole('button', { name: '管理与备份' }).click()
    const drawer = page.getByRole('dialog', { name: `管理项目：${name}` })
    await expect(drawer).toBeVisible()
    return drawer
  }
  try {
    const created = await request.post('/api/v1/conversations', { data: { title: '项目验收100行' } }); const c = await created.json(); ownedConversations.add(c.id)
    const turn = await request.post(`/api/v1/conversations/${c.id}/turns`, { data: { message: '合成Gaia100行验收，不是实际观测。', expected_revision: 0, client_request_id: crypto.randomUUID() } })
    expect(turn.ok()).toBeTruthy()
    await page.goto('/')
    await page.getByRole('complementary', { name: '会话列表' }).getByRole('button', { name: '新建科研项目' }).click()
    const createDialog = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '新建科研项目' }) })
    await createDialog.getByRole('textbox', { name: '项目名称', exact: true }).fill(projectName)
    await createDialog.getByRole('textbox', { name: /项目指令/ }).fill('保留条件、来源和完整结果，不推断成员。')
    const [createdProject] = await Promise.all([
      page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/v1/projects')),
      createDialog.getByRole('button', { name: '创建科研项目', exact: true }).click(),
    ])
    expect(createdProject.status()).toBe(201)
    const { id } = await createdProject.json(); ownedProjects.add(id)
    await expect(createDialog).not.toBeVisible()
    await page.goto('/settings?section=data')
    const drawer = await openManager(projectName, id)
    await drawer.getByRole('tab', { name: /会话与备份/ }).click()
    await chooseUiOption(page, page.getByRole('button', { name: '选择要加入的会话', exact: true }), '项目验收100行')
    await page.getByRole('button', { name: '加入项目', exact: true }).click()
    await expect(drawer.getByRole('button', { name: '移出', exact: true })).toBeVisible()
    await drawer.getByRole('tab', { name: /快照与复核/ }).click()
    await page.getByText('从项目会话保存新快照', { exact: true }).click()
    await chooseUiOption(page, page.getByRole('button', { name: '项目内会话', exact: true }), '项目验收100行')
    await page.getByRole('button', { name: '完整查询结果', exact: true }).click()
    await expect(page.getByRole('listbox').last().getByRole('option')).toHaveCount(2)
    await page.keyboard.press('Escape')
    await page.getByLabel('快照名称', { exact: true }).fill('原始完整样本')
    await page.getByRole('button', { name: '保存完整快照', exact: true }).click()
    await page.getByRole('button', { name: '查看快照 原始完整样本' }).click()
    await page.getByRole('button', { name: '展开数据预览' }).click()
    await expect(page.getByText('查看完整交付表格（100 行）')).toBeVisible()
    await page.getByText('查看完整交付表格（100 行）').click()
    await expect(page.getByRole('cell', { name: '5853498713190525696', exact: true })).toBeVisible()
    await page.getByRole('button', { name: '快速图表与导出', exact: true }).click()
    await page.getByLabel('自行散点图', { exact: true }).check()
    await page.getByRole('button', { name: '生成预览与数据包' }).click()
    await expect(page.getByRole('img', { name: '自行散点图.png', exact: true })).toBeVisible()
    await page.locator('.project-drawer-body').evaluate(el => { el.scrollTop = 0 }); await screenshot('desktop')
    let rerunRequests = 0; page.on('request', r => { if (r.method() === 'POST' && r.url().endsWith('/reruns')) rerunRequests++ })
    await chooseUiOption(page, page.getByRole('button', { name: '选择单条工具查询重跑', exact: true }), 'Gaia DR3 第1次查询')
    await page.getByRole('button', { name: '核对并重跑单条查询' }).click()
    const rerunDialog = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '确认执行这条工具查询？' }) })
    await expect(rerunDialog).toBeVisible(); expect(rerunRequests).toBe(0)
    await rerunDialog.getByRole('button', { name: '取消' }).click()
    await expect(rerunDialog).not.toBeVisible(); expect(rerunRequests).toBe(0)
    await page.getByRole('button', { name: '核对并重跑单条查询' }).click()
    await page.getByRole('button', { name: '确认访问数据源并重跑' }).click()
    await page.getByText(/^直接重跑记录/).click()
    await expect(page.getByRole('button', { name: '查看重跑新快照' })).toBeVisible(); expect(rerunRequests).toBe(1)
    const result = await request.get(`/api/v1/projects/${id}`); const p = await result.json()
    const original = p.snapshots.find((s: { name: string }) => s.name === '原始完整样本'), newer = p.snapshots.find((s: { name: string }) => s.name === '重跑 · gaia')
    for (const cid of p.conversation_ids) ownedConversations.add(cid)
    expect(original.id).not.toBe(newer.id)
    await page.getByText('比较两份快照', { exact: true }).click()
    await chooseUiOption(page, page.getByRole('button', { name: '左侧快照', exact: true }), new RegExp(`原始完整样本 · ${original.id.slice(0, 8)}`))
    await chooseUiOption(page, page.getByRole('button', { name: '右侧快照', exact: true }), new RegExp(`重跑 · gaia · ${newer.id.slice(0, 8)}`))
    await page.getByLabel('按精确 source_id / bibcode 比较交付编号').check()
    await page.getByRole('button', { name: '比较已存快照' }).click()
    await expect(page.getByText('仅比较交付样本与查询元数据；不表示总体增减、显著性或成员变化。')).toBeVisible(); await screenshot('comparison')
    await drawer.getByRole('tab', { name: /会话与备份/ }).click()
    const exportControl = drawer.getByRole('button', { name: '导出项目备份 ZIP' })
    let releaseRefresh!: () => void, observeRefresh!: () => void
    const refreshGate = new Promise<void>(resolve => { releaseRefresh = resolve })
    const refreshStarted = new Promise<void>(resolve => { observeRefresh = resolve })
    await page.route('**/api/v1/projects/memberships', async route => { observeRefresh(); await refreshGate; await route.continue() }, { times: 1 })
    let file
    try {
      const download = page.waitForEvent('download'); await exportControl.click()
      file = await download; expect(file.suggestedFilename()).toBe('astroagent-project.zip')
      await refreshStarted
      await expect(exportControl).toBeDisabled()
    } finally { releaseRefresh() }
    const raw = readFileSync((await file.path())!)
    if (process.env.ASTROAGENT_RECORD_DIR) await file.saveAs(path.join(process.env.ASTROAGENT_RECORD_DIR, `${info.project.name}-project.zip`))
    await expect(exportControl).toBeEnabled()
    await drawer.getByRole('button', { name: '关闭项目管理面板' }).click()
    await expect(drawer).not.toBeVisible()
    const importControl = page.getByLabel('导入 ZIP 备份', { exact: true })
    await expect(importControl).toBeEnabled()
    const importedResponse = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/v1/projects/import'))
    await importControl.setInputFiles({ name: 'restored.zip', mimeType: 'application/zip', buffer: raw })
    const upload = await importedResponse
    expect(upload.status(), await upload.text()).toBe(201)
    const { project: restored } = await upload.json()
    const importedId = restored.id; ownedProjects.add(importedId)
    expect(importedId).not.toBe(id)
    const restoredDrawer = page.getByRole('dialog', { name: `管理项目：${restored.name}` })
    await expect(restoredDrawer.getByText(/导入来源未经认证。归档哈希只验证包内完整性/)).toBeVisible()
    const imported = await (await request.get(`/api/v1/projects/${importedId}`)).json()
    for (const cid of imported.conversation_ids) ownedConversations.add(cid)
    expect(imported.snapshots).toHaveLength(2)
    await restoredDrawer.getByRole('tab', { name: /快照与复核/ }).click()
    await restoredDrawer.getByRole('button', { name: '查看快照 原始完整样本' }).click()
    await restoredDrawer.getByRole('button', { name: '展开数据预览' }).click()
    await expect(restoredDrawer.getByText('查看完整交付表格（100 行）')).toBeVisible()
    await page.reload()
    const reopened = await openManager(restored.name, importedId)
    await reopened.getByRole('tab', { name: /快照与复核/ }).click()
    await reopened.getByRole('button', { name: '查看快照 原始完整样本' }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    await reopened.getByRole('button', { name: '展开数据预览' }).click()
    const mobileResult = reopened.getByRole('complementary', { name: '结果与文件' })
    await expect(mobileResult.getByText('查看完整交付表格（100 行）')).toBeVisible()
    expect(await page.locator('.project-drawer-body').evaluate(el => el.clientHeight)).toBeGreaterThan(200)
    await page.locator('.project-drawer-body').evaluate(el => { el.scrollTop = 0 }); await screenshot('mobile')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await reopened.getByRole('tab', { name: /会话与备份/ }).click()
    await reopened.getByRole('button', { name: '删除项目', exact: true }).click()
    const deleteDialog = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '删除这个科研项目？' }) })
    await expect(deleteDialog).toContainText('会话及其中的消息将移至个人空间')
    await deleteDialog.getByRole('button', { name: '确认删除', exact: true }).click()
    await expect(reopened).not.toBeVisible()
    for (const cid of imported.conversation_ids) expect((await request.get(`/api/v1/conversations/${cid}`)).ok()).toBe(true)
    await expect(importControl).toBeEnabled()
    await importControl.setInputFiles({ name: 'broken.zip', mimeType: 'application/zip', buffer: Buffer.from('broken') })
    await expect(page.getByRole('alert').filter({ hasText: '项目包校验失败' })).toBeVisible()
    expect(errors).toEqual([])
  } finally {
    for (const id of ownedProjects) {
      const response = await request.get(`/api/v1/projects/${id}`)
      if (response.ok()) { const p = await response.json(); await request.delete(`/api/v1/projects/${id}`, { data: { expected_revision: p.revision, confirm: true } }) }
    }
    for (const id of ownedConversations) await request.delete(`/api/v1/conversations/${id}`)
  }
})
