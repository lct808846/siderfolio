import { test, expect } from '@playwright/test'
import { mkdirSync, readFileSync } from 'node:fs'
import path from 'node:path'

test('projects: full snapshots, explicit rerun, compare, ZIP recovery and preserved conversations', async ({ page, request, browser }, info) => {
  info.annotations.push({ type: 'browser_version', description: browser.version() })
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  const ownedProjects = new Set<string>(), ownedConversations = new Set<string>()
  const screenshot = async (name: string) => { if (process.env.ASTROAGENT_RECORD_DIR) { mkdirSync(process.env.ASTROAGENT_RECORD_DIR, { recursive: true }); await page.screenshot({ animations: 'disabled', path: path.join(process.env.ASTROAGENT_RECORD_DIR, `${info.project.name}-project-${name}.png`) }) } }
  try {
    const created = await request.post('/api/v1/conversations', { data: { title: '项目验收100行' } }); const c = await created.json(); ownedConversations.add(c.id)
    const turn = await request.post(`/api/v1/conversations/${c.id}/turns`, { data: { message: '合成Gaia100行验收，不是实际观测。', expected_revision: 0, client_request_id: crypto.randomUUID() } })
    expect(turn.ok()).toBeTruthy()
    await page.goto('/projects')
    await page.getByLabel('项目名称', { exact: true }).fill('候选源复核项目')
    await page.getByLabel('项目说明（可选）').fill('保留条件、来源和完整结果，不推断成员。')
    await page.getByRole('button', { name: '创建项目', exact: true }).click()
    await expect(page.getByRole('heading', { name: '候选源复核项目', exact: true })).toBeVisible()
    const id = new URL(page.url()).pathname.split('/').at(-1)!; ownedProjects.add(id)
    await page.getByLabel('选择要加入的会话').selectOption(c.id)
    await page.getByRole('button', { name: '加入项目', exact: true }).click()
    await expect(page.getByRole('button', { name: '移出项目' })).toBeVisible()
    await page.getByLabel('项目内会话').selectOption(c.id)
    await expect(page.getByLabel('完整响应轮次').locator('option')).toHaveCount(2)
    await page.getByLabel('快照名称', { exact: true }).fill('原始完整样本')
    await page.getByRole('button', { name: '保存完整快照', exact: true }).click()
    await page.getByRole('button', { name: '查看快照 原始完整样本' }).click()
    await expect(page.getByText('查看完整交付表格（100 行）')).toBeVisible()
    await page.getByText('查看完整交付表格（100 行）').click()
    await expect(page.getByRole('cell', { name: '5853498713190525696', exact: true })).toBeVisible()
    await page.getByLabel('自行散点图', { exact: true }).check()
    await page.getByRole('button', { name: '生成预览与数据包' }).click()
    await expect(page.getByRole('img', { name: '自行散点图', exact: true })).toBeVisible()
    await page.locator('.project-main').evaluate(el => { el.scrollTop = 0 }); await screenshot('desktop')
    let rerunRequests = 0; page.on('request', r => { if (r.method() === 'POST' && r.url().endsWith('/reruns')) rerunRequests++ })
    await page.getByLabel('选择单条工具查询重跑').selectOption('gaia:0')
    await page.getByRole('button', { name: '核对并重跑单条查询' }).click()
    await expect(page.getByRole('dialog')).toBeVisible(); expect(rerunRequests).toBe(0)
    await page.keyboard.press('Escape'); await expect(page.getByRole('dialog')).not.toBeVisible(); expect(rerunRequests).toBe(0)
    await page.getByRole('button', { name: '核对并重跑单条查询' }).click()
    await page.getByRole('button', { name: '确认访问数据源并重跑' }).click()
    await expect(page.getByRole('button', { name: '查看重跑新快照' })).toBeVisible(); expect(rerunRequests).toBe(1)
    const result = await request.get(`/api/v1/projects/${id}`); const p = await result.json()
    const original = p.snapshots.find((s: { name: string }) => s.name === '原始完整样本'), newer = p.snapshots.find((s: { name: string }) => s.name === '重跑 · gaia')
    for (const cid of p.conversation_ids) ownedConversations.add(cid)
    expect(original.id).not.toBe(newer.id)
    await page.getByLabel('左侧快照').selectOption(original.id); await page.getByLabel('右侧快照').selectOption(newer.id)
    await page.getByLabel('按精确 source_id / bibcode 比较交付编号').check()
    await page.getByRole('button', { name: '比较已存快照' }).click()
    await expect(page.getByText('仅比较交付样本与查询元数据；不表示总体增减、显著性或成员变化。')).toBeVisible(); await screenshot('comparison')
    const importControl = page.getByLabel('导入项目 ZIP', { exact: true })
    await expect(importControl).toBeEnabled()
    let releaseRefresh!: () => void, observeRefresh!: () => void
    const refreshGate = new Promise<void>(resolve => { releaseRefresh = resolve })
    const refreshStarted = new Promise<void>(resolve => { observeRefresh = resolve })
    await page.route('**/api/v1/projects/memberships', async route => { observeRefresh(); await refreshGate; await route.continue() }, { times: 1 })
    let file
    try {
      const download = page.waitForEvent('download'); await page.getByRole('button', { name: '导出项目 ZIP' }).click()
      file = await download; expect(file.suggestedFilename()).toBe('astroagent-project.zip')
      await refreshStarted
      await expect(importControl).toBeDisabled()
    } finally { releaseRefresh() }
    const raw = readFileSync((await file.path())!)
    if (process.env.ASTROAGENT_RECORD_DIR) await file.saveAs(path.join(process.env.ASTROAGENT_RECORD_DIR, `${info.project.name}-project.zip`))
    // setInputFiles bypasses disabled-control actionability; wait for the export refresh.
    await expect(importControl).toBeEnabled()
    const importedResponse = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/api/v1/projects/import'))
    await importControl.setInputFiles({ name: 'restored.zip', mimeType: 'application/zip', buffer: raw })
    const upload = await importedResponse
    expect(upload.status(), await upload.text()).toBe(201)
    await expect(page).not.toHaveURL(new RegExp(`/projects/${id}`))
    await expect(page.getByText('导入来源未经认证。哈希只验证包内完整性；历史数据不会因导入而重新查询。')).toBeVisible()
    const importedId = new URL(page.url()).pathname.split('/').at(-1)!; ownedProjects.add(importedId)
    const imported = await (await request.get(`/api/v1/projects/${importedId}`)).json()
    for (const cid of imported.conversation_ids) ownedConversations.add(cid)
    expect(imported.snapshots).toHaveLength(2)
    await page.getByRole('button', { name: '查看快照 原始完整样本' }).click()
    await expect(page).toHaveURL(/snapshot=[0-9a-f-]+/)
    await expect(page.getByText('查看完整交付表格（100 行）')).toBeVisible()
    await page.reload(); await expect(page.getByText('查看完整交付表格（100 行）')).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 }); await page.getByRole('button', { name: '项目记录', exact: true }).click()
    expect(await page.locator('.project-main').evaluate(el => el.clientHeight)).toBeGreaterThan(200)
    await page.locator('.project-main').evaluate(el => { el.scrollTop = 0 }); await screenshot('mobile')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.getByRole('button', { name: '删除项目', exact: true }).click()
    await expect(page.getByRole('dialog')).toContainText('会话及其轮次保留')
    await page.getByRole('button', { name: '确认删除', exact: true }).click()
    await expect(page).toHaveURL(/\/projects$/)
    for (const cid of imported.conversation_ids) expect((await request.get(`/api/v1/conversations/${cid}`)).ok()).toBe(true)
    await expect(importControl).toBeEnabled()
    await importControl.setInputFiles({ name: 'broken.zip', mimeType: 'application/zip', buffer: Buffer.from('broken') })
    await expect(page.getByRole('alert')).toContainText('项目包校验失败')
    expect(errors).toEqual([])
  } finally {
    for (const id of ownedProjects) {
      const response = await request.get(`/api/v1/projects/${id}`)
      if (response.ok()) { const p = await response.json(); await request.delete(`/api/v1/projects/${id}`, { data: { expected_revision: p.revision, confirm: true } }) }
    }
    for (const id of ownedConversations) await request.delete(`/api/v1/conversations/${id}`)
  }
})
