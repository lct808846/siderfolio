import { test, expect } from '@playwright/test'

test('synthetic administrator confirms account actions and sees only masked metadata', async ({ page }, info) => {
  await page.goto('/login')
  await page.getByLabel('邮箱', { exact: true }).fill('admin@example.org')
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await page.getByLabel('密码', { exact: true }).fill('Synthetic nebula entropy 2048')
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await page.getByLabel('验证码或恢复码（已启用时填写）').fill('qa-login-' + info.project.name)
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await expect(page).toHaveURL('http://127.0.0.1:5174/')
  await expect(page.locator('a[href="/admin"]')).toHaveCount(0)
  await page.goto('/admin')
  await expect(page.getByRole('heading', { name: '账号与服务状态' })).toBeVisible()
  await expect(page.getByRole('cell', { name: /s\*\*\*@example.org/ })).toBeVisible()
  await expect(page.getByText('second@example.org', { exact: true })).toHaveCount(0)
  await page.getByText('敏感操作重新认证（有效期5分钟）', { exact: true }).click()
  await page.getByLabel('当前密码', { exact: true }).fill('Synthetic nebula entropy 2048')
  await page.getByLabel('验证码或恢复码', { exact: true }).fill('qa-proof-' + info.project.name)
  await page.getByRole('button', { name: '确认身份', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('5分钟')
  const row = page.getByRole('row').filter({ hasText: 's***@example.org' })
  for (const action of ['禁用', '启用', '授予管理员', '撤销管理员']) {
    await row.getByRole('button', { name: action, exact: true }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    await dialog.getByRole('button', { name: '确认操作', exact: true }).click()
    await expect(dialog).not.toBeVisible()
  }
  await page.getByRole('button', { name: '邮件状态', exact: true }).click()
  await expect(page.getByRole('columnheader', { name: '提交状态' })).toBeVisible()
  await page.getByRole('button', { name: '审计日志', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'user_disable', exact: true }).first()).toBeVisible()
})
